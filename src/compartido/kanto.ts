import type { Tipo } from "./tipo-especie";

/**
 * Las 151 especies de Kanto (primera generación): número de la Pokédex, nombre con el que se llama y se pone por
 * omisión, y tipo principal de la primera generación, mapeado a los tipos de la app (config/tipos.json).
 * Es solo la lista del juego: cuáles se pueden sacar lo decide la carpeta de assets (scripts/bajar-sprites.mjs).
 *
 * Cuatro nombres no son una palabra de letras (un nombre propio de la app es una sola palabra, sin símbolos ni puntos),
 * así que traen `titulo` (cómo se ve escrito: «Mr. Mime», «Farfetch'd», «Nidoran♀») y un `nombre` que sí se puede
 * decir, escribir y llamar: Mime, Farfetchd, Nidorana y Nidorano.
 */
export interface EspecieKanto {
  especie: number;
  nombre: string;
  tipo: Tipo;
  /** Cómo se escribe en el juego, si no coincide con `nombre`. */
  titulo?: string;
}

const e = (especie: number, nombre: string, tipo: Tipo, titulo?: string): EspecieKanto =>
  titulo ? { especie, nombre, tipo, titulo } : { especie, nombre, tipo };

